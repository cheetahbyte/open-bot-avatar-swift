#!/usr/bin/env node
// Regenerates the catalog from an open-bot-avatar checkout:
//   node scripts/sync-catalog.mjs [path/to/open-bot-avatar]
// Needs Node 22.18+, which imports the engine's TypeScript directly.
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const source = resolve(process.argv[2] ?? join(here, '../../../open-bot-avatar'));
const target = join(here, '../Sources/OpenBotAvatar/Catalog/AvatarCatalog+Data.generated.swift');

const { examples } = await import(pathToFileURL(join(source, 'packages/core/src/examples.ts')));
const { validateAvatar } = await import(pathToFileURL(join(source, 'packages/core/src/validate.ts')));
const taken = new Set(examples.map((e) => e.id));

const gallery = readdirSync(join(source, 'gallery'))
  .filter((f) => f.endsWith('.json') && f !== 'colors.json')
  .map((f) => {
    const result = validateAvatar(JSON.parse(readFileSync(join(source, 'gallery', f), 'utf8')));
    if (!result.ok) throw new Error(`${f}: ${result.errors.join('; ')}`);
    return result.value;
  })
  .filter((d) => !taken.has(d.id))
  .sort((a, b) => a.name.localeCompare(b.name));
const colors = JSON.parse(readFileSync(join(source, 'gallery/colors.json'), 'utf8'));

const string = (s) => `#"${s}"#`;
const entry = (d) => `    AvatarDefinition(
        id: ${string(d.id)},
        name: ${string(d.name)},
        body: AvatarBody(path: ${string(d.body.path)}),
        eyes: AvatarEyes(x: ${d.eyes.x}, y: ${d.eyes.y}, spacing: ${d.eyes.spacing}, scale: ${d.eyes.scale})
    )`;

writeFileSync(target, `// Generated by scripts/sync-catalog.mjs. Do not edit.

let generatedExamples: [AvatarDefinition] = [
${examples.map(entry).join(',\n')}
]

let generatedGallery: [AvatarDefinition] = [
${gallery.map(entry).join(',\n')}
]

let generatedColors: [String: String] = [
${Object.entries(colors).map(([id, hex]) => `    ${string(id)}: ${string(hex)}`).join(',\n')}
]
`);
